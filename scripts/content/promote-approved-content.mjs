import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { collectContentEvents, getEventDetailAudit, hasText, repoRoot } from "./content-utils.mjs";

const approvedDir = path.join(repoRoot, "content", "approved");
const outputPath = path.join(repoRoot, "outputs", "generated-content.js");
const backupDir = path.join(repoRoot, "content", "generated-backups");
const { events, files } = collectContentEvents(approvedDir);

const cleanEvents = events.map(({ __sourceFile, ...event }) => event);
const approvedIds = new Set(cleanEvents.map((event) => event.id));
const detailLevelCounts = { full: 0, slice: 0, "needs-review": 0, missing: 0 };

const unsafeEvents = cleanEvents.filter((event) => {
  const audit = getEventDetailAudit(event);
  if (!hasText(event.detailLevel)) {
    detailLevelCounts.missing += 1;
    return true;
  }
  detailLevelCounts[event.detailLevel] = (detailLevelCounts[event.detailLevel] || 0) + 1;
  if (event.detailLevel === "needs-review") return true;
  if (!audit.hasBase) return true;
  if (event.detailLevel === "slice" && !audit.hasFullImage) return true;
  if (event.detailLevel === "full" && (!audit.hasFullModal || !audit.hasFullImage)) return true;
  return false;
});

if (unsafeEvents.length) {
  console.error("Refusing to promote unsafe approved event(s). Run content:validate and fix these ids:");
  unsafeEvents.slice(0, 80).forEach((event) => console.error(`- ${event.id || "(missing id)"} (${event.detailLevel || "missing detailLevel"})`));
  if (unsafeEvents.length > 80) console.error(`...and ${unsafeEvents.length - 80} more`);
  process.exit(1);
}

if (fs.existsSync(outputPath)) {
  const sandbox = {};
  vm.createContext(sandbox);
  vm.runInContext(fs.readFileSync(outputPath, "utf8"), sandbox);
  const currentEvents = Array.isArray(sandbox.HISTORY_GENERATED_CONTENT?.events)
    ? sandbox.HISTORY_GENERATED_CONTENT.events
    : [];
  const orphanIds = currentEvents
    .map((event) => event.id)
    .filter((id) => id && !approvedIds.has(id));

  if (orphanIds.length) {
    console.error("Refusing to overwrite generated content because these event id(s) are not present in content/approved:");
    orphanIds.forEach((id) => console.error(`- ${id}`));
    console.error("Move them into content/approved or deliberately remove them before promoting.");
    process.exit(1);
  }

  fs.mkdirSync(backupDir, { recursive: true });
  const stamp = new Date().toISOString().replace(/[:.]/g, "-");
  fs.copyFileSync(outputPath, path.join(backupDir, `generated-content.${stamp}.js`));
}

const content = {
  metadata: {
    generatedAt: new Date().toISOString(),
    sourceFiles: files.map((filePath) => path.relative(repoRoot, filePath)),
    eventCount: cleanEvents.length,
    detailLevelCounts
  },
  events: cleanEvents,
  regionPhases: []
};

const js = `// Generated by scripts/content/promote-approved-content.mjs\n// Only approved content should be emitted here. Candidates and rejected content are never loaded by the app.\nglobalThis.HISTORY_GENERATED_CONTENT = ${JSON.stringify(content, null, 2)};\n`;

fs.writeFileSync(outputPath, js, "utf8");
console.log(`Promoted ${cleanEvents.length} approved event(s) to ${path.relative(repoRoot, outputPath)}`);
